export const deriveCashFloatStatusSummary = (
  requests: CashFloatRequest[]
): CashFloatStatusSummary => {
  const summary: CashFloatStatusSummary = {
    all: requests.length,
    pendingReview: 0,
    approved: 0,
    processing: 0,
    fulfilled: 0,
    rejected: 0,
    cancelled: 0,
  };

  for (const item of requests) {
    switch (item.status) {
      case 'Pending Review':
        summary.pendingReview++;
        break;
      case 'Approved':
        summary.approved++;
        break;
      case 'Processing':
        summary.processing++;
        break;
      case 'Fulfilled':
        summary.fulfilled++;
        break;
      case 'Rejected':
        summary.rejected++;
        break;
      case 'Cancelled':
        summary.cancelled++;
        break;
    }
  }

  return summary;
};
